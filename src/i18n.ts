import { useStore } from './store'

export type Lang = 'en' | 'hr'

// A function declaration with an inline key: the store calls it while this module may still be loading
export function readLang(): Lang {
  try { return localStorage.getItem('obrub-lang') === 'hr' ? 'hr' : 'en' } catch { return 'en' }
}

export const getLang = (): Lang => useStore.getState().lang

export function setLang(l: Lang) {
  try { localStorage.setItem('obrub-lang', l) } catch { /* private mode: only this session */ }
  useStore.setState({ lang: l })
}

// The Croatian text is the key; English falls back to it when a translation is missing
export function t(hr: string, vars?: Record<string, string | number>): string {
  let s = getLang() === 'en' ? EN[hr] ?? hr : hr
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
  return s
}

